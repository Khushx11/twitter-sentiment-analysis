"""Serve the local browser interface."""
import argparse
import json
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ASSETS = Path(__file__).with_name("web_assets")
FILES = {
    "/": ("index.html", "text/html"),
    "/style.css": ("style.css", "text/css"),
    "/app.js": ("app.js", "text/javascript"),
    "/conversation.webp": ("conversation.webp", "image/webp"),
    "/sample.csv": ("sample.csv", "text/csv"),
}

def serve(port, endpoint, process, limit, state=None):
    class Handler(BaseHTTPRequestHandler):
        def send(self, status, kind, content):
            self.send_response(status)
            self.send_header("Content-Type", kind if kind.startswith("image/") else kind + "; charset=utf-8")
            self.send_header("Content-Length", str(len(content)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Content-Security-Policy", "default-src 'self'; frame-ancestors 'none'")
            self.end_headers()
            self.wfile.write(content)

        def send_json(self, status, value):
            self.send(status, "application/json", json.dumps(value, allow_nan=False).encode())

        def do_GET(self):
            if self.path == "/api/session" and state is not None:
                self.send_json(200, state)
                return
            if self.path not in FILES:
                self.send_error(404)
                return
            name, kind = FILES[self.path]
            self.send(200, kind, (ASSETS / name).read_bytes())

        def do_POST(self):
            if self.path != endpoint:
                self.send_error(404)
                return
            origin = self.headers.get("Origin")
            if origin and origin not in {f"http://127.0.0.1:{self.server.server_port}", f"http://localhost:{self.server.server_port}"}:
                self.send_error(403)
                return
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if not 0 < length <= limit:
                    self.send_json(413, {"error": "Request exceeds the input limit or is empty."})
                    return
                body = self.rfile.read(length).decode("utf-8-sig")
                self.send_json(200, process(body))
            except (ValueError, OverflowError) as error:
                self.send_json(400, {"error": str(error)})

    with ThreadingHTTPServer(("127.0.0.1", port), Handler) as server:
        print(f"Open http://127.0.0.1:{server.server_port}", flush=True)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass

from .artefacts import load_bundle
from .data import load
from .inference import predict
from .models import train
from .metrics import score
from .split import split
import numpy as np

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8001)
    parser.add_argument("--model", type=Path, help="Trusted model generated by the training CLI")
    args = parser.parse_args()
    if args.model:
        bundle = load_bundle(args.model)
        classifier = bundle["classifier"]
        evaluation = bundle.get("evaluation")
        state = {"mode": "Local model"}
        if evaluation:
            state["evaluation"] = evaluation
            if evaluation.get("dataset") == "TweetEval sentiment":
                state["mode"] = "TweetEval linear model"
    else:
        train_x, test_x, train_y, test_y = split(*load(ASSETS / "sample.csv"), seed=42)
        classifier, baseline = train(train_x, train_y)
        state = {
            "mode": "Synthetic demo",
            "held_out": len(test_y),
            "model_f1": score(test_y, classifier.predict(test_x))["macro_f1"],
            "baseline_f1": score(test_y, baseline.predict(np.zeros((len(test_y), 1))))["macro_f1"],
        }

    def predict_post(body):
        if len(body) > 1000:
            raise ValueError("Use at most 1,000 characters.")
        return predict(classifier, body)

    serve(args.port, "/api/predict", predict_post, 4096, state)

if __name__ == "__main__":
    main()
